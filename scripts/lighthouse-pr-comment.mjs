#!/usr/bin/env node
// scripts/lighthouse-pr-comment.mjs
//
// Renders a deterministic PR-comment Markdown summarising the most
// recent Lighthouse run. POSTed by a follow-up gh-script step in
// `.github/workflows/lighthouse.yml`.
//
// Reads:
//   .lighthouseci/summary.json (written by lighthouse-publish.mjs)
//   origin/lighthouse-history (last main-branch summary, for delta calc)
//
// Writes:
//   .lighthouseci/pr-comment.md  (Markdown body for the PR comment)
//   .lighthouseci/violations.json (machine-readable list — CI uses for
//                                  threshold gate exit code)
//
// Env vars:
//   GITHUB_REPOSITORY     — e.g. owner/repo (CI-injected, used in HTML link)
//   GITHUB_SHA            — current commit SHA (CI-injected)
//   LIGHTHOUSE_APPROVED   — '1' or 'true' if the override label is present.
//                           When set, threshold violations don't exit 1
//                           (the comment still flags them for visibility).
//
// Exit codes:
//   0 — pass (or warn-only)
//   1 — block (threshold violation AND no override label) —
//       this fails the CI step which fails the status check which
//       blocks the PR merge.
//
// Used by: .github/workflows/lighthouse.yml
//
// Threshold matrix — MUST mirror the FLOOR values in lhci.config.cjs.
// (The LHCI config is the source of truth; this script duplicates the
// numbers for the human-friendly Markdown rendering + regression delta.)
//
//   pwa-home (current FLOOR — ratchet up as fixes land):
//     performance      ≥ 45   (block)
//     accessibility    ≥ 70   (block)   target: 90
//     best-practices   ≥ 85   (block)
//     pwa              ≥ 80   (block)
//   dashboard:
//     performance      ≥ 55   (block — under mobile throttle)
//     accessibility    ≥ 85   (block)
//     best-practices   ≥ 85   (block)
//     pwa              n/a    (dashboard is not a PWA)
//
// Regression thresholds (vs last main-branch run on same page):
//     drop ≥  5 points  →  warn (call out in comment)
//     drop ≥ 10 points  →  block

import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const LHCI_DIR = path.join(REPO_ROOT, '.lighthouseci');
const HISTORY_BRANCH = 'lighthouse-history';
const REMOTE = process.env.LHCI_HISTORY_REMOTE || 'origin';
const REPO = process.env.GITHUB_REPOSITORY || '';
const APPROVED = ['1', 'true', 'yes'].includes(
    String(process.env.LIGHTHOUSE_APPROVED || '').toLowerCase(),
);

const PAGE_THRESHOLDS = {
    'pwa-home':     { performance: 45, accessibility: 70, 'best-practices': 85, pwa: 80 },
    dashboard:      { performance: 55, accessibility: 85, 'best-practices': 85, pwa: null },
};

const REGRESSION_WARN  = 5;   // points
const REGRESSION_BLOCK = 10;  // points

// ── Load current summary (just generated by publish script) ────────────────
function loadCurrent() {
    const p = path.join(LHCI_DIR, 'summary.json');
    if (!fs.existsSync(p)) {
        throw new Error(
            `${p} not found. Run scripts/lighthouse-publish.mjs first.`,
        );
    }
    return JSON.parse(fs.readFileSync(p, 'utf8'));
}

// ── Load baseline (most recent main-branch summary) ────────────────────────
// Returns null when the history branch doesn't exist yet (first ever run).
function loadBaseline() {
    try {
        execSync(`git fetch --depth=20 ${REMOTE} ${HISTORY_BRANCH}`, {
            cwd: REPO_ROOT,
            stdio: 'pipe',
        });
        // The history branch's tree is one folder per SHA. We want the
        // most recent commit's summary.json — `git ls-tree HEAD` gives
        // us the top-level folders sorted by tree order, and the most
        // recently committed one is at HEAD's tree.
        //
        // Simpler: just `git show <branch>:<latest-folder>/summary.json`.
        // Latest-folder = the folder added in HEAD's commit.
        const latestFolder = execSync(
            `git show --name-only --pretty=format: ${REMOTE}/${HISTORY_BRANCH} | ` +
                `head -50 | grep '/summary.json$' | head -1 | cut -d/ -f1`,
            { cwd: REPO_ROOT, shell: '/bin/bash' },
        )
            .toString()
            .trim();
        if (!latestFolder) return null;
        const content = execSync(
            `git show ${REMOTE}/${HISTORY_BRANCH}:${latestFolder}/summary.json`,
            { cwd: REPO_ROOT, stdio: ['pipe', 'pipe', 'pipe'] },
        ).toString();
        return JSON.parse(content);
    } catch (e) {
        // Branch missing or unreadable — first run. Return null and let
        // the comment render without deltas.
        return null;
    }
}

// ── Threshold + regression evaluation ──────────────────────────────────────
function evaluate(current, baseline) {
    const results = [];
    for (const [pageKey, info] of Object.entries(current.pages)) {
        const thresholds = PAGE_THRESHOLDS[pageKey] || {};
        const baselineScores = baseline?.pages?.[pageKey]?.scores || null;
        for (const [metric, score] of Object.entries(info.scores)) {
            if (score == null) continue;
            const min = thresholds[metric];
            const baseScore = baselineScores?.[metric];
            const delta =
                baseScore != null && score != null ? score - baseScore : null;

            // Threshold violation
            if (min != null && score < min) {
                results.push({
                    page: pageKey,
                    metric,
                    score,
                    threshold: min,
                    delta,
                    severity: 'block',
                    reason: `Score ${score} < threshold ${min}`,
                });
                continue;
            }
            // Regression vs baseline
            if (delta != null && delta <= -REGRESSION_BLOCK) {
                results.push({
                    page: pageKey,
                    metric,
                    score,
                    threshold: null,
                    delta,
                    severity: 'block',
                    reason: `Regression ${delta} points vs baseline (${baseScore})`,
                });
            } else if (delta != null && delta <= -REGRESSION_WARN) {
                results.push({
                    page: pageKey,
                    metric,
                    score,
                    threshold: null,
                    delta,
                    severity: 'warn',
                    reason: `Regression ${delta} points vs baseline (${baseScore})`,
                });
            }
        }
    }
    return results;
}

// ── Markdown rendering ─────────────────────────────────────────────────────
function deltaCell(curr, base) {
    if (curr == null) return 'n/a';
    if (base == null) return `${curr}`;
    const d = curr - base;
    const arrow = d > 5 ? '🟢' : d > 0 ? '↗' : d === 0 ? '·' : d > -5 ? '↘' : '🔴';
    const sign = d >= 0 ? '+' : '';
    return `${curr} ${arrow} (${sign}${d})`;
}

function renderScoreTable(current, baseline) {
    const cols = ['performance', 'accessibility', 'best-practices', 'pwa', 'seo'];
    let md = '| Page | ' + cols.map((c) => c[0].toUpperCase() + c.slice(1)).join(' | ') + ' |\n';
    md += '|---|' + cols.map(() => '---:').join('|') + '|\n';
    for (const [pageKey, info] of Object.entries(current.pages)) {
        const baselineScores = baseline?.pages?.[pageKey]?.scores;
        const cells = cols.map((c) => deltaCell(info.scores[c], baselineScores?.[c]));
        md += `| \`${pageKey}\` | ${cells.join(' | ')} |\n`;
    }
    return md;
}

function renderViolations(violations) {
    if (violations.length === 0) {
        return '**Threshold check**: ✅ All pass\n';
    }
    let md = '**Threshold check**: 🔴 ' + violations.length + ' violation(s)\n\n';
    const blocks = violations.filter((v) => v.severity === 'block');
    const warns = violations.filter((v) => v.severity === 'warn');
    if (blocks.length) {
        md += '🔴 **Blockers**:\n';
        for (const v of blocks) {
            const parts = [
                `\`${v.page}\` ${v.metric}`,
                v.reason,
            ];
            if (v.delta != null) parts.push(`Δ ${v.delta >= 0 ? '+' : ''}${v.delta} vs baseline`);
            md += `- ${parts.join(' — ')}\n`;
        }
        md += '\n';
    }
    if (warns.length) {
        md += '🟡 **Warnings**:\n';
        for (const v of warns) {
            md += `- \`${v.page}\` ${v.metric}: ${v.reason}\n`;
        }
        md += '\n';
    }
    return md;
}

function renderApprovalBlock(violations) {
    const blockers = violations.filter((v) => v.severity === 'block');
    if (!blockers.length) return '**Status**: 🟢 PASS\n';
    if (APPROVED) {
        return (
            '**Status**: 🟡 BLOCKERS PRESENT, OVERRIDDEN\n\n' +
            '> The `lighthouse-approved` label is set on this PR. The CI gate has\n' +
            '> been bypassed for this run. Reviewers: confirm the override is\n' +
            '> intentional and document the reason in the merge commit.\n'
        );
    }
    return (
        '**Status**: 🔴 BLOCK\n\n' +
        '> This PR cannot merge until the blockers above are resolved.\n' +
        '> To override: a maintainer can apply the `lighthouse-approved`\n' +
        '> label and re-run the workflow. Use this only when the regression\n' +
        '> is intentional (e.g. shipping a heavy feature behind a flag).\n'
    );
}

function renderComment(current, baseline, violations) {
    let md = `## 🚦 Lighthouse — \`${current.sha}\`\n\n`;
    md += renderScoreTable(current, baseline);
    md += '\n';
    md += renderViolations(violations);
    md += renderApprovalBlock(violations);
    md += '\n';
    md += `<details>\n<summary>Audit settings</summary>\n\n`;
    md += `- **Form factor**: mobile (Slow 4G + 4× CPU slowdown), Moto G Power UA\n`;
    md += `- **Runs per URL**: ${Object.values(current.pages)[0]?.run_count || 'n/a'} (median picked)\n`;
    md += `- **URLs**:\n`;
    for (const [k, info] of Object.entries(current.pages)) md += `  - \`${k}\` — \`${info.url}\`\n`;
    md += `- **Baseline**: ${baseline ? `commit \`${baseline.sha}\` (${baseline.ts})` : 'none yet (first ever run)'}\n`;
    md += `</details>\n\n`;
    if (REPO) {
        md += `📄 [Full HTML reports](https://github.com/${REPO}/tree/${HISTORY_BRANCH}/${current.sha})\n`;
    }
    md += `\n> Want a deeper analysis? Open Claude Code and say *"analyze the latest Lighthouse report"*. Claude Code will pull the JSON from \`${HISTORY_BRANCH}\`, prioritize fixes for low-bandwidth / low-literacy / accessibility, and propose a fix plan you can approve.\n`;
    return md;
}

// ── Main ───────────────────────────────────────────────────────────────────
function main() {
    const current = loadCurrent();
    const baseline = loadBaseline();
    const violations = evaluate(current, baseline);

    const md = renderComment(current, baseline, violations);
    fs.writeFileSync(path.join(LHCI_DIR, 'pr-comment.md'), md);

    fs.writeFileSync(
        path.join(LHCI_DIR, 'violations.json'),
        JSON.stringify(
            {
                sha: current.sha,
                approved: APPROVED,
                violations,
                blockers: violations.filter((v) => v.severity === 'block').length,
                warnings: violations.filter((v) => v.severity === 'warn').length,
            },
            null,
            2,
        ),
    );

    // Echo to stdout for CI logs
    console.log(md);

    const blockerCount = violations.filter((v) => v.severity === 'block').length;
    if (blockerCount > 0 && !APPROVED) {
        console.error(
            `\n❌ ${blockerCount} blocker(s) found and no override label. Failing the gate.`,
        );
        process.exit(1);
    }
    if (blockerCount > 0 && APPROVED) {
        console.log(
            `\n⚠ ${blockerCount} blocker(s) found but \`lighthouse-approved\` label is set — gate bypassed.`,
        );
    }
}

try {
    main();
} catch (e) {
    console.error('[pr-comment] FATAL:', e.message);
    process.exit(2);  // Distinguishable exit: not a threshold violation, but a tool error
}
