#!/usr/bin/env node
/**
 * Sprint C.2 (May 2026) — Inline home-stage i18n subset.
 *
 * Why this exists: the inline `I18N.en` object in app.js is missing
 * ~88 keys that landed AFTER Phase 2 (welcome overlay, device-id tip,
 * UNDP details, lifekeeper pill labels, add_to_homescreen, etc.). Those
 * keys only become available after `_loadLocaleJson('en')` fetches
 * `en.json` and merges. Until then the home stage paints raw key
 * strings ("home_cta_primary" instead of "Report an Incident").
 *
 * The flash is short on fast networks (~100-300 ms) but very visible
 * on slow 3G / cold starts — exactly the UNDP target users.
 *
 * Fix: extract the ~38 keys actually rendered in `<div id="stage-home">`
 * from `i18n/en.json` and splice them into `index.html` as an inline
 * `<script>window.__crispHomeI18nEn = {...}</script>` block. app.js
 * reads this on boot and merges it into `I18N.en` BEFORE the first
 * `applyI18n()` runs, so the home stage paints fully translated on
 * the very first frame.
 *
 * Source-of-truth: the `data-i18n*` attributes inside the
 * `<div id="stage-home">` block of index.html (lines 656-1292 today).
 * Plus a hand-curated set of dynamic-paint keys used by home-screen.js
 * (e.g. `home_login_icon_signed_in`).
 *
 * Cost / benefit:
 *   ~38 keys × ~80 bytes = ~3 KB inline.
 *   Saves the home-stage's UI translation latency (today: 100-500 ms
 *   wait for en.json fetch + parse + merge → 0 ms inline).
 *   Other locales (ar, zh, etc.) still take the JSON path — only EN
 *   gets the inline shortcut. ~95 % of cold loads are EN-default so
 *   the win is broad.
 *
 * Idempotent: re-running with no changes exits 0 and emits no diff.
 *
 *   node scripts/generate-home-i18n-inline.mjs           # rewrite block
 *   node scripts/generate-home-i18n-inline.mjs --check   # CI gate
 */
import { readFile, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const INDEX_PATH = join(ROOT, "mobile-app/src/index.html");
const EN_JSON_PATH = join(ROOT, "mobile-app/src/i18n/en.json");

const CHECK_ONLY = process.argv.includes("--check");
const RED = "\x1b[31m";
const GREEN = "\x1b[32m";
const YELLOW = "\x1b[33m";
const RESET = "\x1b[0m";

const BEGIN_MARK = "<!-- BEGIN HOME_I18N_EN_INLINE (auto-generated by scripts/generate-home-i18n-inline.mjs) -->";
const END_MARK = "<!-- END HOME_I18N_EN_INLINE -->";

// Hand-curated keys used by home-screen.js dynamic painters (not in
// markup attrs, so the index.html scan won't pick them up). Keep this
// list narrow — every key inflates the inline footprint.
const DYNAMIC_HOME_KEYS = [
    "home_greeting_loggedin",      // greeting line after sign-in
    "home_login_icon_signed_in",   // sign-in button label flip
    "home_login_icon_signed_out",
    "home_recent_reports_empty",   // recent-reports empty state
];

function fail(msg) { console.error(`${RED}✘${RESET} ${msg}`); }
function ok(msg)   { console.log(`${GREEN}✓${RESET} ${msg}`); }
function warn(msg) { console.warn(`${YELLOW}⚠${RESET} ${msg}`); }

/**
 * Pull out every `data-i18n[-aria-label|...]="<key>"` attribute inside
 * the `<div id="stage-home">` block (lines 656-1292 today). Robust to
 * arbitrary attribute order on the opening div tag; closes on the
 * NEXT `<div class="stage"` boundary.
 */
function extractHomeKeys(htmlSrc) {
    const openIdx = htmlSrc.indexOf('id="stage-home"');
    if (openIdx === -1) throw new Error('id="stage-home" not found in index.html');
    // Find the start of the line containing the open tag.
    const lineStart = htmlSrc.lastIndexOf("<div", openIdx);
    // The home stage ends at the next stage-class div. Use `<div class="stage `
    // WITH a trailing space so `stage-center`, `stage-header`, etc. inside the
    // home block don't false-match (they're "stage-foo" — no space).
    const closeIdx = htmlSrc.indexOf('<div class="stage ', openIdx + 1);
    const homeBlock = htmlSrc.slice(lineStart, closeIdx === -1 ? htmlSrc.length : closeIdx);

    const keys = new Set();
    const re = /data-i18n(?:-[a-z-]+)?="([^"]+)"/g;
    let m;
    while ((m = re.exec(homeBlock)) !== null) {
        keys.add(m[1]);
    }
    for (const k of DYNAMIC_HOME_KEYS) keys.add(k);
    return [...keys].sort();
}

async function main() {
    const htmlSrc = await readFile(INDEX_PATH, "utf8");
    const enJson = JSON.parse(await readFile(EN_JSON_PATH, "utf8"));

    const homeKeys = extractHomeKeys(htmlSrc);
    const subset = {};
    const missing = [];
    for (const k of homeKeys) {
        if (enJson[k] !== undefined) {
            subset[k] = enJson[k];
        } else {
            missing.push(k);
        }
    }
    if (missing.length) {
        warn(`No EN value for ${missing.length} home key(s): ${missing.join(", ")}`);
        warn(`These will fall back to the inline I18N.en pack (or display raw keys).`);
    }

    // Build the inline block. JSON.stringify inside <script> is safe
    // for all chars EXCEPT a literal `</script>` substring (would close
    // the tag mid-string). Translation values shouldn't contain it but
    // be defensive: escape every `</` to `<\/` per the JSON-in-HTML
    // best-practice (Node.js docs §json-in-script).
    const json = JSON.stringify(subset, null, 4).replace(/<\//g, "<\\/");
    const inlineBlock = [
        BEGIN_MARK,
        "    <script>",
        "        // Inline home-stage translation subset — read by app.js BEFORE",
        "        // the first applyI18n() so the home CTA / brand / footer / etc.",
        "        // paint translated on the very first frame, not after en.json",
        "        // finishes fetching. Auto-generated; re-run",
        "        // `node scripts/generate-home-i18n-inline.mjs` after any en.json edit.",
        `        window.__crispHomeI18nEn = ${json};`,
        "    </script>",
        END_MARK,
    ].join("\n");

    let nextSrc;
    const begin = htmlSrc.indexOf(BEGIN_MARK);
    const end = htmlSrc.indexOf(END_MARK);
    if (begin === -1 || end === -1) {
        // First-time install: splice after the critical-css block so the
        // inline subset is parsed BEFORE any deferred app.js loads.
        const anchor = htmlSrc.indexOf('</style>\n    <!-- ');
        const insertAt = anchor === -1
            ? htmlSrc.indexOf("</head>")
            : htmlSrc.indexOf("\n", anchor) + 1;
        if (insertAt <= 0) {
            fail("Couldn't find an anchor in index.html to splice inline block");
            process.exit(2);
        }
        nextSrc = htmlSrc.slice(0, insertAt) + "    " + inlineBlock + "\n" + htmlSrc.slice(insertAt);
    } else {
        const endIdx = end + END_MARK.length;
        nextSrc = htmlSrc.slice(0, begin) + inlineBlock + htmlSrc.slice(endIdx);
    }

    if (nextSrc === htmlSrc) {
        ok(`home-i18n inline block already in sync (${homeKeys.length} keys, ${json.length} bytes)`);
        process.exit(0);
    }

    if (CHECK_ONLY) {
        fail(`home-i18n drift: re-run \`node scripts/generate-home-i18n-inline.mjs\``);
        process.exit(1);
    }

    await writeFile(INDEX_PATH, nextSrc, "utf8");
    ok(`wrote ${homeKeys.length} home keys (${json.length} bytes inline) to index.html`);
}

main().catch((e) => {
    fail(e.message);
    process.exit(2);
});
