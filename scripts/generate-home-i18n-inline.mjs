#!/usr/bin/env node
/**
 * Generate the inline 22-locale critical-text packs that paint
 * the home + lang-picker + login + channels-sheet surfaces in the user's
 * language on the very first frame — eliminating the visible English
 * flash that previously persisted for ~170 ms (warm) to ~5 s (cold 3G)
 * for non-EN users.
 *
 * Output: a single `window.__crispHomeI18nPacks = { __meta, en, fr, ar, ... }`
 * block spliced into `index.html` between the BEGIN/END markers. Each
 * pack carries:
 *   __version    — first 12 chars of sha256(source i18n/<lang>.json).
 *                  Matches the hash in sw.js manifest for cache parity.
 *   __checksum   — first 16 chars of sha256(pack content) so the runtime
 *                  walker can detect in-transit corruption / build
 *                  artifacts and fall through to the EN pack.
 *   __buildTs    — ISO timestamp from gen-script run. Aids debugging
 *                  ("this build was generated 2 weeks ago — re-run").
 *
 * Scoped to first-frame surfaces only (~80 keys per locale):
 *   #stage-home          — the LCP surface and the first thing users see
 *   #lang-picker-overlay — opened from the home pill within ~3 taps
 *   #channels-sheet      — opened from the "Other ways to report" strip
 *   #stage-login         — secondary CTA surface, reached pre-capture
 *   Plus DYNAMIC_HOME_KEYS for keys used only via JS template strings.
 *
 * v4 capture/classify/review keys are NOT inlined — they're not on the
 * first frame and the existing async _loadLocaleJson path fills them.
 *
 * Total inline footprint: ~50 KB raw / ~12-15 KB gzipped. SW-cached
 * after first visit; effectively free on subsequent loads.
 *
 *   node scripts/generate-home-i18n-inline.mjs           # rewrite block
 *   node scripts/generate-home-i18n-inline.mjs --check   # CI gate
 */
import { readFile, writeFile, readdir } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const INDEX_PATH = join(ROOT, "mobile-app/src/index.html");
const I18N_DIR = join(ROOT, "mobile-app/src/i18n");

const CHECK_ONLY = process.argv.includes("--check");
const RED = "\x1b[31m";
const GREEN = "\x1b[32m";
const YELLOW = "\x1b[33m";
const RESET = "\x1b[0m";

const BEGIN_MARK = "<!-- BEGIN HOME_I18N_EN_INLINE (auto-generated by scripts/generate-home-i18n-inline.mjs) -->";
const END_MARK = "<!-- END HOME_I18N_EN_INLINE -->";

// 22 supported locales — keep in sync with SUPPORTED_LANGS in app.js:4809.
const SUPPORTED_LOCALES = [
    "en", "zh", "es", "ar", "fr", "ru",                       // Tier 1 — UN official
    "hi", "pt", "bn", "ja", "tr", "vi", "ko", "id", "ur",     // Tier 2 — UNDP submission set
    "kn", "ta", "te", "ml", "gu", "mr", "pa",                 // Tier 3 — Indian sub-national
];

// First-frame surfaces. Anything outside these IDs is loaded via the
// async _loadLocaleJson path in app.js — not blocking first paint.
//
// Why only these two:
//   stage-home          — the LCP surface, visible on every cold launch
//   lang-picker-overlay — opens via the always-visible pill at top-right,
//                          so users who land in the wrong lang can switch
//                          before they see any English in the picker
//
// NOT included (user reaches these via gesture; async pack covers them):
//   stage-login          — opens via Login tile tap
//   channels-sheet       — opens via "Other ways to report" tap
//   stage-v4-* (capture flow) — never first-frame
const FIRST_FRAME_SURFACE_IDS = [
    "stage-home",
    "lang-picker-overlay",
];

// Hand-curated keys used by JS template literals (not in markup attrs,
// so the data-i18n scan won't pick them up). Keep narrow.
const DYNAMIC_HOME_KEYS = [
    "home_greeting_loggedin",
    "home_login_icon_signed_in",
    "home_login_icon_signed_out",
    "home_recent_reports_empty",
    "tier_progress_first_report",
    "tier_progress_verified_1",
    "tier_progress_lives_1",
    "tier_progress_top_share",
    "badge_chip_lives_stat",
    "tier_t1_scout_label",
    "tier_t2_signal_label",
    "tier_t3_changemaker_label",
    "tier_t4_lifekeeper_label",
    "empty_submitted",
    "empty_in_flight",
    "mr_empty_filtered",
];

function fail(msg) { console.error(`${RED}✘${RESET} ${msg}`); }
function ok(msg)   { console.log(`${GREEN}✓${RESET} ${msg}`); }
function warn(msg) { console.warn(`${YELLOW}⚠${RESET} ${msg}`); }

function sha256(buf) {
    return createHash("sha256").update(buf).digest("hex");
}

/**
 * Pull every `data-i18n[-aria-label|-placeholder|-title]="<key>"` attribute
 * from each first-frame surface defined by ID. Robust to attribute order
 * on the opening tag; uses the next sibling-stage boundary or the </body>
 * tag as the closer.
 */
function extractFirstFrameKeys(htmlSrc) {
    const keys = new Set();
    const re = /data-i18n(?:-[a-z-]+)?="([^"]+)"/g;

    for (const id of FIRST_FRAME_SURFACE_IDS) {
        const openIdx = htmlSrc.indexOf(`id="${id}"`);
        if (openIdx === -1) {
            warn(`surface id="${id}" not found in index.html — skipping`);
            continue;
        }
        // Backtrack to the start of the open tag.
        const lineStart = htmlSrc.lastIndexOf("<", openIdx);
        // Find a reasonable closer: next sibling stage div, next overlay,
        // or body close. For stages we use ` class="stage ` (with a
        // trailing space so `stage-foo` doesn't false-match its own
        // descendants).
        let closeIdx = htmlSrc.indexOf('class="stage ', openIdx + 1);
        const altClose1 = htmlSrc.indexOf('id="lang-picker-overlay"', openIdx + 1);
        const altClose2 = htmlSrc.indexOf('id="channels-sheet"', openIdx + 1);
        const altClose3 = htmlSrc.indexOf('id="stage-login"', openIdx + 1);
        const altClose4 = htmlSrc.indexOf("</body>", openIdx + 1);
        // Pick the earliest non-self closer (>lineStart + 100 to skip
        // the open tag's own attributes).
        const candidates = [closeIdx, altClose1, altClose2, altClose3, altClose4]
            .filter(i => i > openIdx + 100);
        const blockEnd = candidates.length ? Math.min(...candidates) : htmlSrc.length;

        const block = htmlSrc.slice(lineStart, blockEnd);
        let m;
        // Reset regex global state per block.
        re.lastIndex = 0;
        while ((m = re.exec(block)) !== null) {
            keys.add(m[1]);
        }
    }
    for (const k of DYNAMIC_HOME_KEYS) keys.add(k);
    return [...keys].sort();
}

async function loadAllLocales() {
    const entries = await readdir(I18N_DIR);
    const out = {};
    for (const code of SUPPORTED_LOCALES) {
        const filename = `${code}.json`;
        if (!entries.includes(filename)) {
            throw new Error(`missing locale file: ${filename}`);
        }
        const raw = await readFile(join(I18N_DIR, filename));
        const json = JSON.parse(raw.toString("utf8"));
        out[code] = {
            raw,                            // for hashing
            json,                           // for value lookup
            sourceHash: sha256(raw).slice(0, 12),
        };
    }
    return out;
}

function buildPack(code, locales, keys) {
    const localeJson = locales[code].json;
    const enJson = locales.en.json;
    const pack = {};
    let resolved = 0;
    let enFallback = 0;
    let missing = 0;
    for (const k of keys) {
        if (Object.prototype.hasOwnProperty.call(localeJson, k)) {
            pack[k] = localeJson[k];
            resolved++;
        } else if (Object.prototype.hasOwnProperty.call(enJson, k)) {
            // Locale doesn't have it — fall back to EN value. Better than
            // showing a raw key on first frame.
            pack[k] = enJson[k];
            enFallback++;
        } else {
            // Not in EN either; skip (walker will leave the HTML innerText).
            missing++;
        }
    }
    return { pack, stats: { resolved, enFallback, missing } };
}

async function main() {
    const htmlSrc = await readFile(INDEX_PATH, "utf8");
    const locales = await loadAllLocales();
    const keys = extractFirstFrameKeys(htmlSrc);
    const buildTs = new Date().toISOString();

    const packs = {};
    let totalEnFallback = 0;
    let totalMissing = 0;
    for (const code of SUPPORTED_LOCALES) {
        const { pack, stats } = buildPack(code, locales, keys);
        // Compute checksum of the pack contents (deterministic JSON stringify).
        const packJsonForChecksum = JSON.stringify(pack);
        const checksum = sha256(packJsonForChecksum).slice(0, 16);
        // Inject metadata.
        packs[code] = {
            __version: locales[code].sourceHash,
            __checksum: checksum,
            ...pack,
        };
        if (code !== "en") {
            totalEnFallback += stats.enFallback;
            totalMissing += stats.missing;
        }
    }

    const metaBlock = {
        buildTs,
        scriptVersion: 2,
        keyCount: keys.length,
        locales: SUPPORTED_LOCALES,
    };

    // Build the final inline payload.
    // JSON.stringify is safe inside <script> except for `</script>` which
    // would close the tag mid-string. Escape every `</` to `<\/` per the
    // standard JSON-in-HTML best-practice (web.dev safe-html).
    const payload = JSON.stringify(
        { __meta: metaBlock, ...packs },
        null,
        2,
    ).replace(/<\//g, "<\\/");

    const inlineBlock = [
        BEGIN_MARK,
        "    <script>",
        "        // 22-locale critical-text packs — read by the body-time",
        "        // walker (inline <script> after #stage-home) so the very",
        "        // first frame paints in the user's preferred language.",
        "        // Each pack carries:",
        "        //   __version   — sha256(source i18n/<lang>.json), 12 chars",
        "        //                 matches sw.js manifest hash",
        "        //   __checksum  — sha256(pack content), 16 chars; runtime",
        "        //                 walker uses this to detect corruption",
        "        //   __meta      — buildTs + scriptVersion + key count",
        "        // Auto-generated; re-run",
        "        // `node scripts/generate-home-i18n-inline.mjs` after editing",
        "        // any locale JSON. Pre-commit hook gates drift.",
        `        window.__crispHomeI18nPacks = ${payload};`,
        "    </script>",
        END_MARK,
    ].join("\n");

    let nextSrc;
    const begin = htmlSrc.indexOf(BEGIN_MARK);
    const end = htmlSrc.indexOf(END_MARK);
    if (begin === -1 || end === -1) {
        // First-time install: splice after the critical-css block so the
        // packs are parsed BEFORE any deferred app.js loads.
        const anchor = htmlSrc.indexOf("</style>\n    <!-- ");
        const insertAt = anchor === -1
            ? htmlSrc.indexOf("</head>")
            : htmlSrc.indexOf("\n", anchor) + 1;
        if (insertAt <= 0) {
            fail("Couldn't find an anchor in index.html to splice inline block");
            process.exit(2);
        }
        nextSrc = htmlSrc.slice(0, insertAt) + "    " + inlineBlock + "\n" + htmlSrc.slice(insertAt);
    } else {
        const endIdx = end + END_MARK.length;
        nextSrc = htmlSrc.slice(0, begin) + inlineBlock + htmlSrc.slice(endIdx);
    }

    const sizeKb = (inlineBlock.length / 1024).toFixed(1);

    if (nextSrc === htmlSrc) {
        ok(`home-i18n inline block already in sync (${keys.length} keys × ${SUPPORTED_LOCALES.length} locales, ${sizeKb} KB inline)`);
        if (totalEnFallback || totalMissing) {
            warn(`${totalEnFallback} non-EN key(s) fell back to EN; ${totalMissing} key(s) missing entirely`);
        }
        process.exit(0);
    }

    if (CHECK_ONLY) {
        fail(`home-i18n drift: re-run \`node scripts/generate-home-i18n-inline.mjs\``);
        process.exit(1);
    }

    await writeFile(INDEX_PATH, nextSrc, "utf8");
    ok(`wrote ${keys.length} keys × ${SUPPORTED_LOCALES.length} locales (${sizeKb} KB inline) to index.html`);
    if (totalEnFallback) warn(`${totalEnFallback} non-EN key(s) fell back to EN — translators may want to add these`);
    if (totalMissing) warn(`${totalMissing} key(s) missing from EN — will show HTML innerText fallback`);
}

main().catch((e) => {
    fail(e.message);
    process.exit(2);
});
