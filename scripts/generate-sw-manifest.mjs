#!/usr/bin/env node
/**
 * Sprint C.4 (May 2026) — Workbox-style precache manifest generator.
 *
 * Computes a content hash for every entry in sw.js's STATIC_ASSETS and
 * rewrites the inline `SW_ASSET_MANIFEST` block between the BEGIN/END
 * sentinels. sw.js's install handler uses these hashes to migrate
 * unchanged entries from the previous cache instead of refetching them
 * on every cache-bump.
 *
 * Why per-file hashing instead of one global CACHE_NAME bump:
 *   Today any change to a precached file (even a comment-only edit)
 *   forces a CACHE_NAME bump → all 47 entries re-download on the next
 *   visit, ~1.2 MB cold. With per-file hashes, the install handler
 *   compares each entry's stored hash against the new manifest hash:
 *   * match → copy the Response from the old cache (zero network)
 *   * mismatch → fetch the new version (and tag it with the new hash)
 *   On a typical deploy that touches 3-5 files, returning users now
 *   refetch ~150 KB instead of ~1.2 MB. Bandwidth + battery win.
 *
 * Workflow:
 *   1. Edit any precached file (app.js, styles.css, locale JSON, etc.)
 *   2. Run `node scripts/generate-sw-manifest.mjs`
 *   3. Bump CACHE_NAME in sw.js (still required so the activate handler
 *      knows it's looking at a new SW version) + run
 *      `node scripts/sync-release-tags.mjs`
 *   4. Commit (sw.js + manifest block come along with whatever file you
 *      edited).
 *
 * The generator is idempotent: if every hash already matches the source
 * file content, it exits 0 with no write. CI gate (--check) flags drift.
 *
 *   node scripts/generate-sw-manifest.mjs           # rewrite manifest
 *   node scripts/generate-sw-manifest.mjs --check   # exit non-zero on drift
 */
import { createHash } from "node:crypto";
import { readFile, writeFile, stat } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const SW_PATH = join(ROOT, "mobile-app/src/sw.js");
const SRC_BASE = join(ROOT, "mobile-app/src");

const CHECK_ONLY = process.argv.includes("--check");
const RED = "\x1b[31m";
const GREEN = "\x1b[32m";
const YELLOW = "\x1b[33m";
const RESET = "\x1b[0m";

const BEGIN_MARK = "// ── BEGIN SW_ASSET_MANIFEST (auto-generated by scripts/generate-sw-manifest.mjs) ──";
const END_MARK = "// ── END SW_ASSET_MANIFEST ──";

function fail(msg) { console.error(`${RED}✘${RESET} ${msg}`); }
function ok(msg) { console.log(`${GREEN}✓${RESET} ${msg}`); }
function warn(msg) { console.warn(`${YELLOW}⚠${RESET} ${msg}`); }

/**
 * Pull out every `SW_BASE + 'path'` literal from sw.js's STATIC_ASSETS
 * array. Returns the path-segment strings (e.g. 'app.js', 'i18n/en.json').
 * The bare `SW_BASE` entry (root, which resolves to index.html) is mapped
 * to the empty string '' so callers can treat it specially.
 */
function extractStaticAssetPaths(swSrc) {
    const m = swSrc.match(/const STATIC_ASSETS = \[([\s\S]*?)\];/);
    if (!m) {
        throw new Error("Could not find STATIC_ASSETS array in sw.js");
    }
    const block = m[1];
    const paths = [];
    // Two patterns to match:
    //   SW_BASE + 'app.js'              → 'app.js'
    //   SW_BASE,                        → ''   (bare entry — root → index.html)
    const lineRe = /(?:SW_BASE\s*\+\s*'([^']+)'|^\s*SW_BASE\s*,?\s*(?:\/\/[^\n]*)?$)/gm;
    let match;
    while ((match = lineRe.exec(block)) !== null) {
        paths.push(match[1] || "");
    }
    return paths;
}

async function hashFile(filepath) {
    const data = await readFile(filepath);
    return createHash("sha256").update(data).digest("hex").slice(0, 12);
}

async function main() {
    const swSrc = await readFile(SW_PATH, "utf8");
    const assetPaths = extractStaticAssetPaths(swSrc);
    if (assetPaths.length === 0) {
        fail("No STATIC_ASSETS entries parsed — check the regex");
        process.exit(2);
    }

    const manifest = {};
    const missing = [];
    for (const relpath of assetPaths) {
        // Root entry (empty path) maps to index.html on disk.
        const onDisk = relpath || "index.html";
        const fullpath = join(SRC_BASE, onDisk);
        try {
            await stat(fullpath);
            manifest[onDisk] = await hashFile(fullpath);
        } catch (_e) {
            missing.push(onDisk);
        }
    }
    if (missing.length) {
        warn(`Skipped ${missing.length} missing file(s): ${missing.join(", ")}`);
    }

    // Build the new manifest block — fixed-key ordering keeps diffs minimal.
    const sortedKeys = Object.keys(manifest).sort();
    const lines = [BEGIN_MARK, "const SW_ASSET_MANIFEST = {"];
    for (const k of sortedKeys) {
        lines.push(`    ${JSON.stringify(k)}: ${JSON.stringify(manifest[k])},`);
    }
    lines.push("};", END_MARK);
    const newBlock = lines.join("\n");

    // Locate the existing block. If absent, splice it in right before the
    // STATIC_ASSETS declaration so install-handler code below it can see
    // the constant. Idempotent — re-running the script just rewrites the
    // body between the sentinels.
    let nextSrc;
    const begin = swSrc.indexOf(BEGIN_MARK);
    const end = swSrc.indexOf(END_MARK);
    if (begin === -1 || end === -1) {
        // First-time install: splice before `const STATIC_ASSETS`.
        const anchor = swSrc.indexOf("const STATIC_ASSETS = [");
        if (anchor === -1) {
            fail("Couldn't find STATIC_ASSETS declaration to splice manifest before");
            process.exit(2);
        }
        nextSrc =
            swSrc.slice(0, anchor) +
            newBlock + "\n\n" +
            swSrc.slice(anchor);
    } else {
        // Replace existing block (from BEGIN_MARK through END_MARK + newline).
        const endIdx = end + END_MARK.length;
        nextSrc = swSrc.slice(0, begin) + newBlock + swSrc.slice(endIdx);
    }

    if (nextSrc === swSrc) {
        ok(`manifest already in sync (${sortedKeys.length} entries)`);
        process.exit(0);
    }

    if (CHECK_ONLY) {
        fail(`manifest drift: re-run \`node scripts/generate-sw-manifest.mjs\` to regenerate`);
        process.exit(1);
    }

    await writeFile(SW_PATH, nextSrc, "utf8");
    ok(`wrote ${sortedKeys.length} asset hashes to ${SW_PATH}`);
}

main().catch((e) => {
    fail(e.message);
    process.exit(2);
});
